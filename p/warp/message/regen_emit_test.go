func mustEmit(msg message.Payload, err error) message.Payload {
	if err != nil {
		panic(err)
	}
	return msg
}

func goByteLiteral(b []byte) string {
	parts := make([]string, len(b))
	for i, v := range b {
		parts[i] = fmt.Sprintf("0x%02x", v)
	}
	return "[]byte{" + strings.Join(parts, ", ") + "}"
}
